// Regenerates lib/location-coordinates.ts from OpenStreetMap (Nominatim).
// Run from the project root: node scripts/geocode.mjs
// Review the output afterwards; any location listed under MISSING needs coordinates added by hand.
import { readFileSync, writeFileSync } from 'node:fs'

const src = readFileSync('lib/locations.ts', 'utf8')
const entries = [...src.matchAll(/place\('((?:[^'\\]|\\.)*)',\s*'(North|Central)'/g)].map((m) => ({
  name: m[1],
  campus: m[2],
}))
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

function slug(value) {
  return value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/\s+/g, '-')
}

function queries(name) {
  const noQuotes = name.replace(/\("[^"]*"\)/g, '').replace(/"/g, '')
  const noParens = noQuotes.replace(/\([^)]*\)/g, ' ')
  const keepParens = noQuotes.replace(/[()]/g, ' ')
  const firstPart = noParens.split(',')[0]
  return [...new Set([noParens, keepParens, firstPart].map((q) => q.replace(/[:]/g, '').replace(/\s+/g, ' ').trim()))]
}

async function geocode(q) {
  const url = `https://nominatim.openstreetmap.org/search?format=json&limit=1&viewbox=-76.50,42.465,-76.46,42.433&bounded=1&q=${encodeURIComponent(q)}`
  const res = await fetch(url, { headers: { 'User-Agent': 'sustainabytes-nme-geocode/1.0' } })
  if (!res.ok) return null
  const data = await res.json()
  return data[0] ? [Number(Number(data[0].lat).toFixed(6)), Number(Number(data[0].lon).toFixed(6))] : null
}

const lines = []
const missing = []
for (const { name, campus } of entries) {
  let hit = null
  for (const q of queries(name)) {
    try {
      hit = await geocode(q)
    } catch {}
    await sleep(1100)
    if (hit) break
  }
  const id = `${campus.toLowerCase()}-${slug(name)}`
  if (hit) lines.push(`  '${id}': [${hit[0]}, ${hit[1]}],`)
  else missing.push(id)
  console.log(name, '=>', hit ? hit.join(',') : 'MISS')
}

writeFileSync(
  'lib/location-coordinates.ts',
  `/** [latitude, longitude] for each location id in lib/locations.ts. Generated by scripts/geocode.mjs. */
export const LOCATION_COORDINATES: Record<string, [number, number]> = {
${lines.join('\n')}
}
`,
)
console.log('MISSING:', JSON.stringify(missing))
